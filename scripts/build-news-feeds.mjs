// Merge verified per-region feed research into the desktop's bundled news registry.
// Usage: node scripts/build-news-feeds.mjs <research-dir-with-*.json>
// Writes apps/desktop/src/main/news/newsFeeds.json and docs/data/news-feeds.json (with evidence).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const repo = resolve(import.meta.dirname, '..')
const dir = resolve(process.argv[2] ?? '.')
const files = readdirSync(dir).filter((name) => name.endsWith('.json'))
const feeds = []
const gaps = []
const seenIds = new Set()
const seenUrls = new Set()
const problems = []
const bcp47 = /^[A-Za-z]{2,8}(?:-[A-Za-z0-9]{1,8})*$/
const scopes = new Set(['national', 'regional', 'local'])

for (const file of files.sort()) {
  const data = JSON.parse(readFileSync(join(dir, file), 'utf8'))
  for (const gap of data.gaps ?? []) gaps.push({ ...gap, region: data.region })
  for (const raw of data.feeds ?? []) {
    const where = `${file}:${raw.sourceId}`
    const id = String(raw.sourceId ?? '').toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 64)
    const url = String(raw.url ?? '')
    const format = raw.check?.format === 'atom' ? 'atom' : raw.check?.format === 'rss' ? 'rss' : null
    if (!id || !/^[A-Z]{2}$/.test(raw.countryCode ?? '') || !/^https?:\/\//.test(url) || !format) { problems.push(`${where}: missing id/country/url/format`); continue }
    if (raw.check?.status !== 200 || !(raw.check?.items > 0)) { problems.push(`${where}: did not pass check`); continue }
    if (seenIds.has(id) || seenUrls.has(url)) { problems.push(`${where}: duplicate`); continue }
    seenIds.add(id)
    seenUrls.add(url)
    const tags = (Array.isArray(raw.languageTags) ? raw.languageTags : []).map(String).filter((tag) => bcp47.test(tag))
    feeds.push({
      sourceId: id,
      countryCode: raw.countryCode,
      url,
      format,
      publisherName: String(raw.publisherName ?? id).slice(0, 160),
      publisherType: String(raw.publisherType ?? 'newspaper').slice(0, 40),
      section: String(raw.section ?? 'news').slice(0, 80),
      languageTags: tags.length ? tags : ['und'],
      geographicScope: scopes.has(raw.geographicScope) ? raw.geographicScope : 'national',
      regionName: raw.regionName ? String(raw.regionName).slice(0, 120) : null,
      cityName: raw.cityName ? String(raw.cityName).slice(0, 120) : null,
      independentPublisherGroupId: String(raw.independentPublisherGroupId ?? id).toLowerCase().replace(/[^a-z0-9-]+/g, '-').slice(0, 64),
      termsUrl: typeof raw.termsUrl === 'string' && /^https?:\/\//.test(raw.termsUrl) ? raw.termsUrl : null,
      evidence: {
        checkedAt: data.checkedAt ?? null,
        status: raw.check.status,
        items: raw.check.items,
        newest: raw.check.newest ?? null,
        termsNote: raw.termsNote ?? 'not found',
        sampleTitles: (raw.sampleTitles ?? []).slice(0, 2),
      },
    })
  }
}
feeds.sort((a, b) => a.countryCode.localeCompare(b.countryCode) || a.sourceId.localeCompare(b.sourceId))
const countries = new Set(feeds.map((feed) => feed.countryCode))
const generatedAt = new Date().toISOString().slice(0, 10)
writeFileSync(join(repo, 'apps/desktop/src/main/news/newsFeeds.json'), `${JSON.stringify({
  schemaVersion: '1.0',
  generatedAt,
  note: 'Generated by scripts/build-news-feeds.mjs. Evidence and gaps: docs/data/news-feeds.json.',
  feeds: feeds.map(({ evidence, ...feed }) => feed),
}, null, 1)}\n`)
writeFileSync(join(repo, 'docs/data/news-feeds.json'), `${JSON.stringify({
  schemaVersion: '1.0',
  generatedAt,
  admission: 'Admitted by the product owner on 2026-10-26 for the desktop prototype: headline, link, id and publish time only; no bodies, images or descriptions are stored; 3-day retention; 20-minute polling with conditional requests. Per-source terms review remains open (SOURCE_APPROVAL).',
  countryCount: countries.size,
  feedCount: feeds.length,
  feeds,
  gaps,
}, null, 1)}\n`)
console.log(`feeds ${feeds.length}, countries ${countries.size}, gaps ${gaps.length}`)
if (problems.length) console.log(`skipped:\n  ${problems.join('\n  ')}`)
