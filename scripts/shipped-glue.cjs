'use strict'

// Mozilla's bergamot-translator glue is MPL-2.0. It ships unchanged as a file of its own
// (out/main/vendor/bergamot-translator.js) and is read from there at run time; none of its text may
// be compiled into Intoponet's own files. This checks a build's output for both. The release
// packaging runs it after building (scripts/package-macos.cjs), and so does scripts/shipped-glue.test.cjs.

const { createHash } = require('node:crypto')
const { existsSync, readFileSync, readdirSync, statSync } = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const VENDORED_GLUE = path.join(root, 'apps/desktop/src/main/translate/vendor/bergamot-translator.js')
/** Where the copy sits in a build, relative to the build output (apps/desktop/out). */
const SHIPPED_GLUE = 'main/vendor/bergamot-translator.js'
/** The file as copied from Firefox (vendor/README.md, THIRD_PARTY_NOTICES.md §2). */
const GLUE_SHA256 = 'faff1ef6285b0d26f01787776fd49299dfb756ecb9688aa990c250e66797b47d'

const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex')

function scripts(dir, found = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) scripts(file, found)
    else if (/\.(js|cjs|mjs|html|map)$/.test(entry.name)) found.push(file)
  }
  return found
}

/**
 * Lines of the glue to look for in other files: its header, and a spread of its longer lines.
 * Lines a bundler would escape inside a string (backslash, backtick, dollar) are left out, so a
 * copy embedded as text is still found.
 */
function glueMarkers(text) {
  const lines = text.split('\n').map((line) => line.trim()).filter((line) => line.length >= 48 && !/[\\`$]/.test(line))
  const unique = [...new Set(lines)]
  const step = Math.max(1, Math.floor(unique.length / 40))
  const sampled = unique.filter((_, index) => index % step === 0)
  const header = unique.filter((line) => /This Source Code Form is subject to the terms of the Mozilla Public|generated by inference\/scripts\/build-wasm\.py/.test(line))
  return [...new Set([...header, ...sampled])]
}

/**
 * Throws unless the build output at `outDir` ships the vendored glue byte for byte as its own file
 * and no other script in it contains the glue's text.
 */
function checkShippedGlue({ outDir = path.join(root, 'apps/desktop/out'), vendored = VENDORED_GLUE, expectedSha256 = GLUE_SHA256 } = {}) {
  if (!existsSync(vendored)) throw new Error(`the vendored glue is missing: ${vendored}`)
  const vendoredSha = sha256(vendored)
  if (vendoredSha !== expectedSha256) throw new Error(`the vendored glue has been changed: SHA-256 ${vendoredSha}, recorded ${expectedSha256}`)
  if (!existsSync(outDir) || !statSync(outDir).isDirectory()) throw new Error(`there is no build output at ${outDir}; run npm run build`)
  const shipped = path.join(outDir, SHIPPED_GLUE)
  if (!existsSync(shipped)) throw new Error(`the build does not ship the glue as its own file (${SHIPPED_GLUE})`)
  const shippedSha = sha256(shipped)
  if (shippedSha !== vendoredSha) throw new Error(`the shipped glue differs from the vendored file: SHA-256 ${shippedSha}, expected ${vendoredSha}`)

  const markers = glueMarkers(readFileSync(vendored, 'utf8'))
  if (markers.length < 10) throw new Error('too few lines of the glue to search for')
  const others = scripts(outDir).filter((file) => path.resolve(file) !== path.resolve(shipped))
  if (!others.some((file) => path.relative(outDir, file) === path.join('main', 'index.js'))) {
    throw new Error(`the build output has no main/index.js under ${outDir}`)
  }
  for (const file of others) {
    const text = readFileSync(file, 'utf8')
    const found = markers.find((marker) => text.includes(marker))
    if (found) throw new Error(`${path.relative(outDir, file)} contains text of the MPL-2.0 glue ("${found.slice(0, 60)}"); it must ship only as ${SHIPPED_GLUE}`)
  }
  return { shipped, sha256: shippedSha, scanned: others.length, markers: markers.length }
}

module.exports = { checkShippedGlue, glueMarkers, GLUE_SHA256, SHIPPED_GLUE, VENDORED_GLUE }
