// Privacy › Sites to leave out: no recent page, no Absorb.
export default async function ({ evaluate, shotApp, delay, send }) {
  await delay(3000)
  await evaluate(`[...document.querySelectorAll('.bookmark-library-button')].find((b) => b.innerText.includes('My map')).click(); true`)
  await delay(800)
  await evaluate(`[...document.querySelectorAll('.drawer-tabs button')].find((b) => b.innerText.includes('Privacy')).click(); true`)
  await delay(600)
  await evaluate(`document.querySelector('.privacy-site-form input').focus(); true`)
  await send('Input.insertText', { text: 'https://www.example.com/' })
  await delay(200)
  await evaluate(`document.querySelector('.privacy-site-form button[type=submit]').click(); true`)
  await delay(800)
  console.log('list', await evaluate(`[...document.querySelectorAll('.privacy-sites li')].map((li) => li.innerText).join(',')`))
  await shotApp('privacy-excluded-sites')
  await evaluate(`window.intoponet.browserHost.open({ kind: 'url', value: 'https://example.com/' }); true`)
  await delay(5000)
  await evaluate(`window.intoponet.browserHost.open({ kind: 'url', value: 'https://www.iana.org/' }); true`)
  await delay(5000)
  const lib = await evaluate(`window.intoponet.browserHost.readPrivateLibrary().then((r) => r.status === 'ok' && r.payload ? JSON.parse(r.payload).recents.map((p) => p.url).join(' | ') : 'none')`)
  console.log('recents', lib)
  await evaluate(`window.intoponet.browserHost.activateTab ? window.intoponet.browserHost.getTabs().then((t) => window.intoponet.browserHost.activateTab(t.find((x) => x.url.includes('example.com')).id)) : null`)
  await delay(1500)
  console.log('absorb', await evaluate(`window.intoponet.knowledge.preview('article').then((p) => p.refused ? 'refused: ' + p.reason : 'ALLOWED')`))
}
